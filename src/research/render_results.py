"""Render the measured-results table from results/model_comparison.json.

The table is written between marker comments in README.md and research/report.md,
so every number in those documents comes from the saved experiment files.

    python -m src.research.render_results
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parents[2]
COMPARISON_PATH = ROOT_DIR / "results" / "model_comparison.json"
TARGET_DOCS = [ROOT_DIR / "README.md", ROOT_DIR / "research" / "report.md"]
START = "<!-- RESULTS_TABLE_START -->"
END = "<!-- RESULTS_TABLE_END -->"

DISPLAY_NAMES = {
    "baseline_cnn": "BaselineCNN",
    "resnet18": "ResNet18",
    "resnet18_aug": "ResNet18 + augmentation",
}


def run_scope(metrics: dict[str, Any]) -> str:
    """Describe how much data the run used, based only on what was recorded."""
    if "max_samples" not in metrics:
        return "not recorded"
    if metrics["max_samples"] is None:
        return "full dataset"
    return f"SMOKE RUN ({metrics['max_samples']} samples per split)"


def _fmt(value: Any, template: str) -> str:
    return template.format(value) if isinstance(value, (int, float)) else "n/a"


def build_table(comparison: dict[str, dict[str, Any]]) -> str:
    header = (
        "| Model | Accuracy | Macro F1 | Training time | Test inference time | "
        "Parameters | Epochs | Run scope |"
    )
    rows = [header, "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for name, metrics in comparison.items():
        rows.append(
            "| {model} | {acc} | {f1} | {train} | {infer} | {params} | {epochs} | {scope} |".format(
                model=DISPLAY_NAMES.get(name, name),
                acc=_fmt(metrics.get("accuracy"), "{:.4f}"),
                f1=_fmt(metrics.get("f1_macro"), "{:.4f}"),
                train=_fmt(metrics.get("training_time_seconds"), "{:.1f} s"),
                infer=_fmt(metrics.get("inference_time_seconds"), "{:.2f} s"),
                params=_fmt(metrics.get("num_parameters"), "{:,}"),
                epochs=metrics.get("epochs", "n/a"),
                scope=run_scope(metrics),
            )
        )
    return "\n".join(rows)


def build_warnings(comparison: dict[str, dict[str, Any]]) -> list[str]:
    warnings = []
    for name, metrics in comparison.items():
        label = DISPLAY_NAMES.get(name, name)
        if "max_samples" not in metrics:
            warnings.append(
                f"{label}: run scope was not recorded (produced by an older version of the code). "
                "Re-run training to confirm it used the full dataset."
            )
        if metrics.get("max_samples") is not None:
            warnings.append(f"{label} is a smoke run and must not be used for conclusions.")
        if metrics.get("num_predicted_classes", 9) < 9:
            warnings.append(
                f"{label} predicted only {metrics['num_predicted_classes']} of 9 classes (class collapse)."
            )
    epochs = {m.get("epochs") for m in comparison.values()}
    if len(epochs) > 1:
        warnings.append(
            "Models were trained for different numbers of epochs "
            f"({', '.join(str(e) for e in sorted(epochs, key=str))}); this is not a like-for-like comparison."
        )
    return warnings


def render_block(comparison: dict[str, dict[str, Any]]) -> str:
    parts = [START, "", build_table(comparison)]
    warnings = build_warnings(comparison)
    if warnings:
        parts += ["", "\n>\n".join(f"> **Caution:** {w}" for w in warnings)]
    parts += ["", "_Generated by `python -m src.research.render_results` from `results/model_comparison.json`._", "", END]
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise ValueError(f"Markers {START} / {END} not found")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return before + block + after


def main() -> None:
    comparison = json.loads(COMPARISON_PATH.read_text(encoding="utf-8"))
    block = render_block(comparison)
    for doc in TARGET_DOCS:
        doc.write_text(replace_block(doc.read_text(encoding="utf-8"), block), encoding="utf-8")
        print(f"Updated results table in {doc.relative_to(ROOT_DIR)}")


if __name__ == "__main__":
    main()
